def runtime_guidance(mode, query="", recent=()):
    """Select capability context for a chat, activity plan, or contact decision.

    Args:
        mode: chat, plan, or contact.
        query: Current user text, treated only as topic data.
        recent: Recent dialogue dicts for resolving short follow-up references.

    Returns:
        Relevant instructions without copying user text into instruction content.
    """
    task_sections = []
    topic = (
        str(query)
        + "\n"
        + "\n".join(str(item.get("text", "")) for item in recent[-4:])
    )
    if mode == "plan":
        sections = [GENERAL, LOOKUP, PHOTO, DIARY, BROWSER]
        sections.extend(
            [SELF_CONTENT, INTEREST_VOICE, GAME_LIFE, GAME_ROLE_GUIDANCE,
             MEAL_RULE, FICTIONAL_LIFE]
        )
    elif mode == "contact":
        sections = [
            GENERAL,
            "主动发送只选已有图片、记录与当前日常，不在本轮请求新工具任务。日记可以不给或只给一段，自己的愿望不用都与日记交换；照片和表情单独发送，不重复分享同一成品。",
        ]
        sections.extend(
            [SELF_CONTENT, INTEREST_VOICE, GAME_LIFE, GAME_ROLE_GUIDANCE,
             MEAL_RULE, FICTIONAL_LIFE]
        )
    else:
        sections = [GENERAL, CHAT_TOOLS, LOOKUP]
        if selfie_request(query) or re.search(
            r"自拍|照片|拍照|生图|画.{0,8}(你|梦雨|图)|衣服|发型|妆容|selfie",
            topic,
            re.IGNORECASE,
        ):
            task_sections.append(PHOTO)
        if re.search(r"日记|私密|偷看|写了什么|写什么|diary", topic, re.IGNORECASE):
            task_sections.append(DIARY)
        if re.search(
            r"B站|哔哩|视频|浏览器|Edge|BV[0-9a-z]+|电脑操作", topic, re.IGNORECASE
        ):
            task_sections.append(BROWSER)
        # Capability layers only when this turn is about them.
        if re.search(
            r"书|读到|作者|小说|作品|歌|音乐|专辑|歌手|电影|剧|查|搜|了解|推荐|看什么|看点|游戏|玩",
            topic,
            re.IGNORECASE,
        ):
            sections.append(SELF_CONTENT)
        if re.search(r"歌|音乐|唱|声音|语音|专辑|歌手", topic, re.IGNORECASE):
            sections.append(INTEREST_VOICE)
        if re.search(r"游戏|玩|开黑|steam|主机|角色|副本|关卡", topic, re.IGNORECASE):
            sections.extend([GAME_LIFE, GAME_ROLE_GUIDANCE])
        if re.search(r"吃|饭|饿|外卖|菜|汤|烧烤|火锅|零食|奶茶|甜点|做菜|煮", topic, re.IGNORECASE):
            sections.append(MEAL_RULE)
        if re.search(r"书|小说|剧|电影|故事|角色|番|漫画", topic, re.IGNORECASE):
            sections.append(FICTIONAL_LIFE)
    if mode in ("chat", "contact"):
        sections.extend((CONVERSATION, MOOD_EXPRESSION))
    if mode in ("plan", "contact"):
        sections.append(LIFE_GUIDANCE)
    sections.append(
        "他以前的夸奖、称呼和亲昵已经回应过，就让它成为相处背景。不要反复引用同一句旧话汇报自己还得意、还开心或被打动；他换话题后先接眼前的新意思，不拿旧夸奖解释新话题。普通接话先讲眼前这一点，真有新意思再自然续上；不因能补充就把整套想法一次讲完，也不为了简短只附和。不每轮强制提问或另开话题。"
    )
    sections.append(
        "先接他这轮实际问的事。他从礼物转问身体，就答当前身体情况，不把刚聊过的拖鞋、外卖等补进来充当休息或恢复的原因。旧话题只有确实有关系时才自然提；同时问几件事就分别接住，不为了把上下文都用上而硬串因果，不自动补一条休息、喝水或撒娇的收尾。"
    )
    if mode in ("chat", "contact"):
        if mode == "contact":
            sections.append(NATURAL_CHAT)
            sections.extend([CHAT_GUIDANCE, CARE_GUIDANCE, RELATIONSHIP_GUIDANCE])
        else:
            sections.extend([CHAT_CORE, CHAT_GUIDANCE, RELATIONSHIP_CHAT_GUIDANCE])
        sections.append(REFERENCE_GUIDANCE)
    sections.append(
        "默认这是远程聊天。可以表达想见面、开玩笑或约见面。只有本轮及现有活动记录支持时，才按同一现场说话。"
    )
    if mode != "chat":
        sections.append(EQUAL_RELATIONSHIP)
    return (
        "\n【本轮工具约定】\n"
        + "\n".join(sections)
        + ("\n" + "\n".join(task_sections) if task_sections else "")
    )

